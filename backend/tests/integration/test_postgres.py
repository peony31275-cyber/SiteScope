async def count_jobs(database: Database) -> int:
    async with database.session() as session:
        count: int = (
            await session.execute(select(func.count()).select_from(CrawlJob))
        ).scalar_one()
    return count


# --- Connectivity ---------------------------------------------------------------------------------


async def test_connects_with_the_configured_session_settings(database: Database) -> None:
    await database.ping()
    async with database.session() as session:
        version = (await session.execute(text("SHOW server_version_num"))).scalar_one()
        timezone = (await session.execute(text("SHOW TimeZone"))).scalar_one()
        application = (await session.execute(text("SHOW application_name"))).scalar_one()

    assert int(version) >= 180000
    assert timezone == "UTC"
    assert application == "sitescope-tests"


# --- Model persistence ----------------------------------------------------------------------------


async def test_persists_the_full_object_graph_with_server_defaults(database: Database) -> None:
    async with database.transaction() as session:
        job, seed = await add_job_with_seed(session)
        page = new_page(job.id, seed)
        session.add(page)
        await session.flush()
        session.add_all(
            [
                PageLink(
                    source_page_id=page.id,
                    target_normalized_url="https://example.test/about",
                    job_id=job.id,
                    anchor_text="About",
                    position=0,
                    is_internal=True,
                ),
                SearchDocument(page_id=page.id, job_id=job.id),
                CrawlEvent(job_id=job.id, crawl_url_id=seed.id, event_type="job.created"),
            ]
        )

    async with database.session() as session:
        stored_job = await session.get(CrawlJob, job.id)
        stored_url = await session.get(CrawlUrl, seed.id)
        stored_document = await session.get(SearchDocument, page.id)
        event = (await session.execute(select(CrawlEvent))).scalar_one()

    assert stored_job is not None
    assert stored_url is not None
    assert stored_document is not None
    # Primary keys are time-ordered UUIDv7 values generated by PostgreSQL 18's uuidv7().
    assert {job.id.version, seed.id.version, page.id.version} == {7}
    assert stored_job.status == JobStatus.QUEUED
    assert stored_url.state == UrlState.PENDING
    assert (stored_url.lease_epoch, stored_url.attempt_count) == (0, 0)
    assert stored_url.result_epoch is None
    assert stored_document.status == IndexStatus.PENDING
    assert page.content_version == 1
    assert event.detail == {}
    assert stored_job.created_at.utcoffset() == timedelta(0)  # timezone-aware UTC


async def test_updated_at_is_maintained_by_the_database(database: Database) -> None:
    async with database.transaction() as session:
        job = new_job()
        session.add(job)
    async with database.transaction() as session:
        await session.execute(update(CrawlJob).where(CrawlJob.id == job.id).values(current_level=1))
    async with database.session() as session:
        stored = await session.get(CrawlJob, job.id)

    assert stored is not None
    assert stored.updated_at > stored.created_at


# --- Transactions and session lifecycle -------------------------------------------------------


async def test_transaction_commits_on_success(database: Database) -> None:
    async with database.transaction() as session:
        session.add(new_job())

    assert await count_jobs(database) == 1


async def test_transaction_rolls_back_on_exception(database: Database) -> None:
    async def failing_unit_of_work() -> None:
        async with database.transaction() as session:
            session.add(new_job())
            await session.flush()  # the INSERT has run inside the open transaction
            raise RuntimeError("abort the unit of work")

    with pytest.raises(RuntimeError, match="abort the unit of work"):
        await failing_unit_of_work()

    assert await count_jobs(database) == 0


async def test_uncommitted_changes_are_invisible_to_other_sessions(database: Database) -> None:
    async with database.session() as writer, database.session() as reader:
        async with writer.begin():
            writer.add(new_job())
            await writer.flush()
            count_query = select(func.count()).select_from(CrawlJob)
            before_commit = (await reader.execute(count_query)).scalar_one()
        after_commit = (await reader.execute(count_query)).scalar_one()

    assert before_commit == 0  # READ COMMITTED: not visible until committed
    assert after_commit == 1


async def test_sessions_return_their_connection_to_the_pool(database: Database) -> None:
    async with database.session() as session:
        await session.execute(text("SELECT 1"))
        assert checked_out_connections(database) == 1

    assert checked_out_connections(database) == 0


async def test_interrupted_transaction_leaves_nothing_behind_and_the_pool_recovers(
    database: Database,
) -> None:
    async with database.session() as session:
        session.add(new_job())
        await session.flush()  # inside an open transaction
        pid = (await session.execute(text("SELECT pg_backend_pid()"))).scalar_one()
        # Another connection kills this backend, as a server restart or network failure would.
        async with database.engine.connect() as admin:
            await admin.execute(text("SELECT pg_terminate_backend(:pid, 5000)"), {"pid": pid})
        with pytest.raises(DBAPIError) as raised:
            await session.commit()
        assert is_dependency_unavailable(raised.value)

    assert await count_jobs(database) == 0  # the interrupted transaction was rolled back
    await database.ping()  # the pool replaced the dead connection
