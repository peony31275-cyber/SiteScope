"""Regenerate the backend's Linux lock files: ``runtime.txt`` (the Docker image) and ``dev.txt``
(runtime plus the ``dev`` extra: CI and the tests).

Run it with the image's Python, from the repository root (Docker in WSL on Windows)::

    docker run --rm -v "$PWD/backend:/src" -w /src python:3.13.16-slim-trixie \
        python requirements/lock.py

pip's resolver reads ``pyproject.toml``, constrained by the current ``dev.txt``. So a pin
changes only when ``pyproject.toml`` needs another version, or for a ``--constraint`` file given
(the first lock used the versions the test suite had run with). ``--upgrade`` drops the
constraints and takes the newest versions allowed. Review the diff and run the tests with the
new versions before committing them.

The pins are versions, not hashes: one lock serves amd64 and arm64 images.
"""

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parent
HEADER = (
    "# {purpose}\n"
    "# Exact versions for CPython 3.13 on Linux, generated by requirements/lock.py from\n"
    "# pyproject.toml (see its docstring). Do not edit by hand.\n"
)
SETS = {
    "runtime": ("", "Runtime dependencies of the backend's Docker image."),
    "dev": ("[dev]", "Runtime and development dependencies (CI: lint, types, tests)."),
}


def resolve(source: Path, extra: str, constraints: list[Path], report: Path) -> list[str]:
    command = [sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed"]
    command += ["--quiet", "--report", str(report)]
    for constraint in constraints:
        command += ["--constraint", str(constraint)]
    subprocess.run([*command, f"{source}{extra}"], check=True)  # noqa: S603 - fixed program
    installed = json.loads(report.read_text(encoding="utf-8"))["install"]
    pins = [
        f"{item['metadata']['name']}=={item['metadata']['version']}"
        for item in installed
        if item["metadata"]["name"] != "sitescope-backend"
    ]
    return sorted(pins, key=str.lower)


def main() -> int:
    if sys.platform != "linux":
        sys.stderr.write("Run this inside a Linux container (see the docstring).\n")
        return 2
    parser = argparse.ArgumentParser(description="Regenerate requirements/runtime.txt and dev.txt.")
    parser.add_argument("--constraint", type=Path, action="append", default=[])
    parser.add_argument("--upgrade", action="store_true", help="ignore the current pins")
    args = parser.parse_args()
    constraints: list[Path] = list(args.constraint)
    if not args.upgrade and (HERE / "dev.txt").is_file():
        constraints.append(HERE / "dev.txt")
    with tempfile.TemporaryDirectory() as temporary:
        work = Path(temporary)
        # pip writes build metadata into the project: resolve a copy, never the source tree.
        source = work / "src"
        shutil.copytree(
            PROJECT,
            source,
            ignore=shutil.ignore_patterns(
                ".venv", "*.egg-info", "__pycache__", "*_cache", "tests", "requirements"
            ),
        )
        for name, (extra, purpose) in SETS.items():
            pins = resolve(source, extra, constraints, work / f"{name}.json")
            text = HEADER.format(purpose=purpose) + "\n".join(pins) + "\n"
            (HERE / f"{name}.txt").write_text(text, encoding="utf-8", newline="\n")
            sys.stdout.write(f"{name}.txt: {len(pins)} packages\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
